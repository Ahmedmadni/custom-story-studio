def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("upload", type=Path)
    args = parser.parse_args()
    destination = Path("public/drawing")
    sheets = []
    credits = ["دفعة الرسومات الإضافية المرفقة من صاحب الموقع (19 قالبًا فريدًا):",
               "أكد مالك الموقع امتلاكه إذن إعادة النشر من المصادر المذكورة أدناه.",
               "الرسومات حُولت من ملفات PDF إلى WebP مع إبقاء العلامات الظاهرة داخل الصفحات.", ""]
    assert len(PAGES) == len({row[1] for row in PAGES}) == 19
    for filename, slug, title, group, provider in PAGES:
        document = fitz.open(args.upload / filename)
        assert len(document) == 1
        key = "attachment-" + slug
        make_sheet(document[0], (.01, .01, .99, .99), destination / key)
        sheets.append({"id": key, "title": title, "group": group})
        credits.append(f"{title} — {filename} — {provider}")
        document.close()
    credits.extend(["", "Cinderella-at-the-Royal-Ball-coloring (1).pdf نسخة مطابقة تمامًا؛ لم تُضف مرة ثانية.",
                    "ملفا Flamingos 75+ وTurtles 350+ يحتوي كل منهما على صفحة واحدة، لا 75 أو 350 صورة.",
                    "مصادر SketchJoy: https://www.sketchjoy.com/batman-coloring-pages/ و https://www.sketchjoy.com/cinderella-coloring-pages/",
                    "مصدر HP Printables: https://printables.hp.com/",
                    "مصدر SuperColoring: https://www.supercoloring.com/search/coloring/flamingos و https://www.supercoloring.com/search/coloring/turtles"])
    (destination / "attachment-credits.txt").write_text("\n".join(credits) + "\n", encoding="utf-8")
    Path("src/features/games/drawing/extra-catalog.ts").write_text(
        "// Generated by scripts/import_more_pdfs.py from the owner's permitted attachments.\n"
        "export const extraSheets = " + json.dumps(sheets, ensure_ascii=False, indent=2) + " as const;\n", encoding="utf-8")
    print(f"Imported {len(sheets)} unique attached PDF coloring sheets")


if __name__ == "__main__":
    main()
